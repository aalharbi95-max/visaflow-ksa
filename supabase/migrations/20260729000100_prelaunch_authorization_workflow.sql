-- This preflight is deliberately after agency_id creation but before backfill.
-- Ambiguous/unmatched legacy agency names are reported and skipped.
do $agency_link_preflight$
declare
  linkable_count bigint;
  ambiguous_count bigint;
  unmatched_count bigint;
  inactive_agency_count bigint;
begin
  with matches as (
    select authorization_row.id,
      count(distinct access.agency_id) filter (
        where access.status = 'Active' and agency.status = 'Active'
      ) active_matches,
      count(distinct access.agency_id) filter (
        where agency.status is distinct from 'Active'
      ) inactive_matches
    from public.visa_authorizations authorization_row
    left join public.company_agency_access access
      on access.company_id = authorization_row.company_id
    left join public.agencies agency
      on agency.id = access.agency_id
     and lower(trim(agency.name)) = lower(trim(authorization_row.agency))
    where authorization_row.agency_id is null
    group by authorization_row.id
  )
  select count(*) filter (where active_matches = 1),
    count(*) filter (where active_matches > 1),
    count(*) filter (where active_matches = 0),
    count(*) filter (where inactive_matches > 0)
  into linkable_count, ambiguous_count, unmatched_count, inactive_agency_count
  from matches;

  raise notice 'prelaunch agency link preflight: linkable=%, ambiguous=%, unmatched=%, inactive_agency=%',
    linkable_count, ambiguous_count, unmatched_count, inactive_agency_count;
end;
$agency_link_preflight$;

