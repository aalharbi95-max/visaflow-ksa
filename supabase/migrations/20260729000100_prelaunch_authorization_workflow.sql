-- Backfill legacy name-only assignments only when the company has exactly one
-- active agency with that normalized name. Ambiguous rows stay unassigned and
-- must be reviewed instead of being exposed to the wrong agency.
with unambiguous_agency_matches as (
  select
    authorization_row.id as authorization_id,
    (array_agg(distinct access.agency_id))[1] as agency_id
  from public.visa_authorizations authorization_row
  join public.company_agency_access access
    on access.company_id = authorization_row.company_id
   and coalesce(access.status, 'Active') = 'Active'
  join public.agencies agency
    on agency.id = access.agency_id
   and agency.status = 'Active'
   and lower(trim(agency.name)) = lower(trim(authorization_row.agency))
  where authorization_row.agency_id is null
  group by authorization_row.id
  having count(distinct access.agency_id) = 1
)
update public.visa_authorizations authorization_row
set agency_id = matched.agency_id
from unambiguous_agency_matches matched
where authorization_row.id = matched.authorization_id;

insert into public.authorization_events (
  authorization_id,
  company_id,
  agency_id,
  event_type,
  actor_name,
  actor_email,
  actor_role,
  idempotency_key,
  created_at,
  metadata
)
select
  authorization_row.id,
  authorization_row.company_id,
  authorization_row.agency_id,
  'Created',
  coalesce(nullif(authorization_row.created_by_name, ''), 'Legacy Import'),
  nullif(authorization_row.created_by_email, ''),
  coalesce(nullif(authorization_row.created_by_role, ''), 'System'),
  'legacy-created:' || authorization_row.id::text,
  coalesce(authorization_row.created_at, now()),
  jsonb_build_object('backfilled', true)
from public.visa_authorizations authorization_row
where authorization_row.company_id is not null
  and not exists (
    select 1
    from public.authorization_events event
    where event.authorization_id = authorization_row.id
      and event.event_type = 'Created'
  );

